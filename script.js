let favorites = JSON.parse(localStorage.getItem('favWorks')) || [];

function renderGrid(filter = 'all') {
  const grid = document.getElementById('content-grid');
  grid.innerHTML = "";
  const filtered = filter === 'all' ? data : data.filter(item => item.cat === filter);
  
  filtered.forEach(item => {
    const isFav = favorites.includes(item.id);
    const readingTime = Math.ceil(item.text.split(' ').length / 150);
    grid.innerHTML += `
                <div class="card">
                    <button class="fav-btn" onclick="toggleFavorite(${item.id})">${isFav ? '❤️' : '🤍'}</button>
                    <div style="display:flex; justify-content:space-between; align-items:center; width: 85%;">
                        <span style="font-size:0.7rem; background:var(--accent); color:white; padding:2px 10px; border-radius:10px;">${item.cat === 'poem' ? 'কবিতা' : 'গল্প'}</span>
                        <small style="opacity:0.6;">⏱️ ${readingTime} মি. পাঠ</small>
                    </div>
                    <h3 style="margin-top:10px;">${item.title}</h3>
                    <p style="margin:10px 0; opacity:0.8;">${item.text.substring(0, 80)}...</p>
                    <button onclick="openModal(${item.id})" style="color:var(--accent); border:none; background:none; cursor:pointer; font-weight:bold;">বিস্তারিত পড়ুন →</button>
                </div>`;
  });
}

function toggleFavorite(id) {
  const index = favorites.indexOf(id);
  if (index > -1) {
    favorites.splice(index, 1);
  } else {
    favorites.push(id);
  }
  localStorage.setItem('favWorks', JSON.stringify(favorites));
  renderGrid();
}

function searchContent() {
  let input = document.getElementById('searchInput').value.toLowerCase();
  let cards = document.getElementsByClassName('card');
  for (let card of cards) {
    let title = card.querySelector('h3').innerText.toLowerCase();
    card.style.display = title.includes(input) ? "" : "none";
  }
}

function copyText() {
  const text = document.getElementById('modalBody').innerText;
  navigator.clipboard.writeText(text);
  alert("লেখাটি কপি হয়েছে! এবার আপনার প্রিয়জনকে পাঠান।");
}

function changeFontSize(size) {
  document.getElementById('modalBody').style.fontSize = size + "rem";
}

function openModal(id) {
  const item = data.find(d => d.id === id);
  document.getElementById('modalTitle').innerText = item.title;
  document.getElementById('modalBody').innerText = item.text;
  document.getElementById('textModal').style.display = "flex";
  document.body.style.overflow = "hidden";
}

function closeModal() {
  document.getElementById('textModal').style.display = "none";
  document.body.style.overflow = "auto";
}

function openAboutModal() {
  document.getElementById('aboutModal').style.display = "flex";
  document.body.style.overflow = "hidden";
}

function closeAboutModal() {
  document.getElementById('aboutModal').style.display = "none";
  document.body.style.overflow = "auto";
}

function filterData(category, btn) {
  document.querySelectorAll('.btn').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');
  renderGrid(category);
}

const themeBtn = document.getElementById('theme-toggle');
themeBtn.addEventListener('click', () => {
  document.body.classList.toggle('dark-mode');
  themeBtn.innerText = document.body.classList.contains('dark-mode') ? "লাইট মোড" : "ডার্ক মোড";
});

// Close modals on outside click
window.onclick = function(event) {
  if (event.target.className === 'modal') {
    closeModal();
    closeAboutModal();
  }
}

window.onload = () => renderGrid('all');